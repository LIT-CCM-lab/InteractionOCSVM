import argparse
import sys
import pdb
import numpy as np
import pickle
import os
import logging
import pandas as pd

def main(args):
    
    models = []
    for cls_file in args.classifier:
        with open(cls_file, 'rb') as f:
            models.append(pickle.load(f))

    print('Evaluating interactions')

    for file in args.file:
        with open(file, 'rb') as f:
            inter = pickle.load(f)
            #ifps = inter.read_ifp()
            if args.simplify:
                inter.simplify_hb(in_place = True)
            ifps = inter.fingerprints
            ifps = ifp.remove_empty_ints(ifps)


        for igocsvm_model in models:
            logging.info(f'Rescroing using IG-OCSVM: {igocsvm_model.description}')
            model_ifps = ifp.filter_ifp(ifps, igocsvm_model.ig_info['Residues'], igocsvm_model.ig_info['Interactions'])
            scores = igocsvm_model.score(model_ifps.sparse.to_dense())
            if scores is None:
                continue
            logging.info(f'Docking poses selected: {len(scores[scores >= 0])} / {len(ifps)}\n')
            print(f'Docking poses selected: {len(scores[scores >= 0])} / {len(ifps)}\n')
            results_dict = {'Protein_structure': inter.receptor_mol2, 'Ligand_pose': inter.ligand_mol2, 'Score': scores}
            #pdb.set_trace()
            pd.DataFrame.from_dict(results_dict).to_csv(f'{os.path.splitext(os.path.basename(file))[0]}_{igocsvm_model.description}_results.csv', index = False)

    print('Calculations completed')


if __name__ == "__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument('-c', '--classifier', nargs = '+', help = 'File containing the kernel and ocsvm file forming a classifier', required = True)
    parser.add_argument('-f', '--file', nargs = '+', help='Inuput map file generated by a script calculating the interactions', required = True)
    parser.add_argument('-s', '--simplify', default = False, action = 'store_true')


    parser.set_defaults(func=main)
    args=parser.parse_args()
    status = args.func(args)
    sys.exit(status)