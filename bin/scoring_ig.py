import argparse
import sys
import pdb
import numpy as np
import pickle
import os
import logging
import pandas as pd

def main(args):
    
    ref_ig_info = {'threshold': args.thresh,
                   'subgraph': args.subgraph,
                   'round_val': 1,
                   'simplify': args.simplify,
                   'mode': args.mode}
    print('Loading models')
    models = []
    for cls_file in args.classifier:
        with open(cls_file, 'rb') as f:
            models.append(pickle.load(f))



    print('Evaluating interactions')

    for file in args.file:
        with open(file, 'rb') as f:
            logging.info(f'Evaluating interactions in {args.file}')
            inter = pickle.load(f)
            g = inter.compute_graphs(subgraph = args.subgraph,
                                              simplify = args.simplify,
                                              mode = args.mode,
                                              threshold = args.thresh)
        logging.info(f'Interaction graphs generated for rescoring: {len(g)}\n')
        ng = np.array([gt.n for gt in g])
        mask = ng > 2
        g = g[mask]

        for igocsvm_model in models:
            logging.info(f'Rescroing using IG-OCSVM: {igocsvm_model.description}')
            scores_tmp = igocsvm_model.score(g, ref_ig_info, inter.ipa_info)
            if scores_tmp is None:
                continue
            scores = np.full(len(mask), np.nan)
            scores[mask]=scores_tmp
            logging.info(f'Docking poses selected: {len(scores[scores >= 0])} / {len(g)}\n')
            results_dict = {'Protein_structure': inter.receptor_mol2, 'Ligand_pose': inter.ligand_mol2, 'IPA': inter.output_location, 'Score': scores}
            pd.DataFrame.from_dict(results_dict).to_csv(f'{os.path.splitext(os.path.basename(file))[0]}_{igocsvm_model.description}_results.csv', index = False)

    print('Calculations completed')


if __name__ == "__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument('-c', '--classifier', nargs = '+', help = 'File containing the kernel and ocsvm file forming a classifier', required = True)
    parser.add_argument('-f', '--file', nargs = '+', help='Inuput map file generated by a script calculating the interactions', required = True)
    parser.add_argument('-t', '--type', default = 'MERG', help='type of interactions used in interaction detection.\navailble types: MERG, CENT, LIG, PROT')
    parser.add_argument('-sg', '--subgraph', default = 'MERG', help='Available subgraph types: CENT, LIG, PROT, ELEC')
    parser.add_argument('-s', '--simplify', default = False, help= 'simplify representation of hydrogen bonds', action = 'store_true')
    parser.add_argument('-mo', '--mode', default = 'grakel', help = 'type of interaction graph')
    parser.add_argument('-th', '--thresh', default = None, help = 'distance threshold for edge in interaction graph', type = float)

    parser.set_defaults(func=main)
    args=parser.parse_args()
    status = args.func(args)
    sys.exit(status)